/** @file test_build_timestamp.c
 *
 *  Standalone unit test for src/base/build_timestamp.c: the BUILD_DATE and
 *  BUILD_TIME strings are populated.
 *
 *  Prints one line per failing check and a summary; exit status is 0 if all
 *  checks pass, 1 otherwise.
 *
 *  This is a libbase unit test: it links the internal libbase/libutil
 *  convenience libraries directly.
 */

